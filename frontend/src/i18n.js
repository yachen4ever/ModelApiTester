export function getInitialLang() {
  let lang = localStorage.getItem('lang') || (navigator.language?.startsWith('zh') ? 'zh' : 'en');
  if (!I18N[lang]) lang = 'en';
  return lang;
}

export function t(lang, key) {
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}
